// func sdpaQueriesDim32NoMaskAVX2Asm(
//     qPtr, kPtr, vPtr, outPtr, scoresPtr unsafe.Pointer,
//     qByteStride, kvByteStride, numQueries, kvLen, qStart, causalInt int,
//     scale float32,
// )
TEXT ·sdpaQueriesDim32NoMaskAVX2Asm(SB), NOSPLIT, $0-92
	MOVQ qPtr+0(FP), SI
	MOVQ kPtr+8(FP), R8
	MOVQ vPtr+16(FP), R9
	MOVQ outPtr+24(FP), DI
	MOVQ scoresPtr+32(FP), R10
	MOVQ kvByteStride+48(FP), R11
	MOVQ numQueries+56(FP), R13
	MOVQ qStart+72(FP), R14

	TESTQ R13, R13
	JLE sdpa256_done

	LEAQ (R11)(R11*2), R12
	LEAQ ·sdpaAVX2Consts(SB), DX
	VMOVUPS 128(DX), Y14 // Y14 = vMagic (12582912.0)
	VMOVUPS 416(DX), Y15 // Y15 = vOne (1.0f) / vBias127 (127 << 23)

query256_loop:
	MOVQ kvLen+64(FP), R15
	MOVQ causalInt+80(FP), AX
	TESTQ AX, AX
	JZ check256_kv_len
	LEAQ 1(R14), AX
	CMPQ AX, R15
	CMOVQLT AX, R15

check256_kv_len:
	TESTQ R15, R15
	JG valid256_query

zero256_query_out:
	VXORPS Y0, Y0, Y0
	VMOVUPS Y0, 0(DI)
	VMOVUPS Y0, 32(DI)
	VMOVUPS Y0, 64(DI)
	VMOVUPS Y0, 96(DI)
	JMP next256_query

valid256_query:
	// Load query[0:32] into Y0..Y3 and pre-scale by scale
	VBROADCASTSS scale+88(FP), Y4
	VMOVUPS 0(SI), Y0
	VMOVUPS 32(SI), Y1
	VMOVUPS 64(SI), Y2
	VMOVUPS 96(SI), Y3
	VMULPS Y4, Y0, Y0
	VMULPS Y4, Y1, Y1
	VMULPS Y4, Y2, Y2
	VMULPS Y4, Y3, Y3

	// --- STAGE 1: Q @ K^T (4 keys per iteration) ---
	VMOVUPS 0(DX), X10 // X10 = [-Inf, -Inf, -Inf, -Inf]
	MOVQ R8, AX
	MOVQ R10, BX
	MOVQ R15, CX

stage1_256_loop4:
	CMPQ CX, $4
	JL stage1_256_reduce_max4

	// Interleave Key 0..3 across Y4..Y7 to hide 4-cycle FMA latency
	VMULPS 0(AX), Y0, Y4
	VMULPS 0(AX)(R11*1), Y0, Y5
	VMULPS 0(AX)(R11*2), Y0, Y6
	VMULPS 0(AX)(R12*1), Y0, Y7

	VFMADD231PS 32(AX), Y1, Y4
	VFMADD231PS 32(AX)(R11*1), Y1, Y5
	VFMADD231PS 32(AX)(R11*2), Y1, Y6
	VFMADD231PS 32(AX)(R12*1), Y1, Y7

	VFMADD231PS 64(AX), Y2, Y4
	VFMADD231PS 64(AX)(R11*1), Y2, Y5
	VFMADD231PS 64(AX)(R11*2), Y2, Y6
	VFMADD231PS 64(AX)(R12*1), Y2, Y7

	VFMADD231PS 96(AX), Y3, Y4
	VFMADD231PS 96(AX)(R11*1), Y3, Y5
	VFMADD231PS 96(AX)(R11*2), Y3, Y6
	VFMADD231PS 96(AX)(R12*1), Y3, Y7

	// Fold 256-bit Y4..Y7 -> 128-bit X4..X7
	VEXTRACTF128 $1, Y4, X8
	VEXTRACTF128 $1, Y5, X9
	VEXTRACTF128 $1, Y6, X11
	VEXTRACTF128 $1, Y7, X12
	VADDPS X8, X4, X4
	VADDPS X9, X5, X5
	VADDPS X11, X6, X6
	VADDPS X12, X7, X7

	// Transpose-and-add 4x4 X4..X7 -> X4 = [dot0, dot1, dot2, dot3]
	VUNPCKLPS X5, X4, X8
	VUNPCKHPS X5, X4, X4
	VUNPCKLPS X7, X6, X9
	VUNPCKHPS X7, X6, X6
	VADDPS X4, X8, X4
	VADDPS X6, X9, X6
	VSHUFPS $0x44, X6, X4, X8
	VSHUFPS $0xEE, X6, X4, X4
	VADDPS X4, X8, X4

	VMOVUPS X4, (BX)
	VMAXPS X4, X10, X10

	LEAQ (AX)(R11*4), AX
	ADDQ $16, BX
	SUBQ $4, CX
	JMP stage1_256_loop4

stage1_256_reduce_max4:
	VPERMILPS $0xEE, X10, X11
	VMAXPS X11, X10, X10
	VPERMILPS $0x01, X10, X11
	VMAXSS X11, X10, X10

stage1_256_rem:
	TESTQ CX, CX
	JLE stage1_256_pad

	VMULPS 0(AX), Y0, Y4
	VFMADD231PS 32(AX), Y1, Y4
	VFMADD231PS 64(AX), Y2, Y4
	VFMADD231PS 96(AX), Y3, Y4

	VEXTRACTF128 $1, Y4, X5
	VADDPS X5, X4, X4
	VPERMILPS $0xEE, X4, X5
	VADDPS X5, X4, X4
	VPERMILPS $0x01, X4, X5
	VADDSS X5, X4, X4

	VMOVSS X4, (BX)
	VMAXSS X4, X10, X10

	ADDQ R11, AX
	ADDQ $4, BX
	DECQ CX
	JMP stage1_256_rem

stage1_256_pad:
	VUCOMISS 0(DX), X10
	JBE zero256_query_out
	JP zero256_query_out

	// Pad 8 float32s at scoresScratch[kvLenUnmasked] with -Inf
	VMOVUPS 0(DX), Y4
	VMOVUPS Y4, (BX)

	// --- STAGE 2: SOFTMAX exp256(scores - rowMax) ---
	VBROADCASTSS X10, Y10 // Y10 = vRowMax
	VXORPS Y11, Y11, Y11  // Y11 = vSum
	MOVQ R10, BX
	MOVQ R15, CX

stage2_256_loop8:
	VMOVUPS (BX), Y2
	VSUBPS Y10, Y2, Y2
	VMAXPS 32(DX), Y2, Y2
	VMINPS 64(DX), Y2, Y2

	VMOVAPS Y14, Y3
	VFMADD231PS 96(DX), Y2, Y3
	VSUBPS Y14, Y3, Y4
	VPSLLD $23, Y3, Y3
	VPADDD Y15, Y3, Y3

	VFNMADD231PS 160(DX), Y4, Y2
	VFNMADD231PS 192(DX), Y4, Y2

	VMULPS Y2, Y2, Y4
	VMOVUPS 256(DX), Y5
	VFMADD231PS 224(DX), Y2, Y5
	VMOVUPS 320(DX), Y6
	VFMADD231PS 288(DX), Y2, Y6
	VMOVUPS 384(DX), Y7
	VFMADD231PS 352(DX), Y2, Y7
	VADDPS Y15, Y2, Y8
	VMULPS Y4, Y4, Y9
	VFMADD213PS Y6, Y4, Y5
	VFMADD213PS Y8, Y4, Y7
	VFMADD213PS Y7, Y9, Y5
	VMULPS Y3, Y5, Y2

	VMOVUPS Y2, (BX)
	VADDPS Y2, Y11, Y11

	ADDQ $32, BX
	SUBQ $8, CX
	JG stage2_256_loop8

	// Horizontal sum of Y11 -> scalar X11[0]
	VEXTRACTF128 $1, Y11, X12
	VADDPS X12, X11, X11
	VPERMILPS $0xEE, X11, X12
	VADDPS X12, X11, X11
	VPERMILPS $0x01, X11, X12
	VADDSS X12, X11, X11

	VDIVSS X11, X15, X11

	// --- STAGE 3: VALUE ACCUMULATION (4x unrolled, 8 YMM accumulators Y0..Y7) ---
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7

	MOVQ R9, AX
	MOVQ R10, BX
	MOVQ R15, CX

stage3_256_loop4:
	CMPQ CX, $4
	JL stage3_256_loop2

	VBROADCASTSS 0(BX), Y8
	VBROADCASTSS 4(BX), Y9
	VBROADCASTSS 8(BX), Y10
	VBROADCASTSS 12(BX), Y12

	VFMADD231PS 0(AX), Y8, Y0
	VFMADD231PS 32(AX), Y8, Y1
	VFMADD231PS 64(AX), Y8, Y2
	VFMADD231PS 96(AX), Y8, Y3

	VFMADD231PS 0(AX)(R11*1), Y9, Y4
	VFMADD231PS 32(AX)(R11*1), Y9, Y5
	VFMADD231PS 64(AX)(R11*1), Y9, Y6
	VFMADD231PS 96(AX)(R11*1), Y9, Y7

	VFMADD231PS 0(AX)(R11*2), Y10, Y0
	VFMADD231PS 32(AX)(R11*2), Y10, Y1
	VFMADD231PS 64(AX)(R11*2), Y10, Y2
	VFMADD231PS 96(AX)(R11*2), Y10, Y3

	VFMADD231PS 0(AX)(R12*1), Y12, Y4
	VFMADD231PS 32(AX)(R12*1), Y12, Y5
	VFMADD231PS 64(AX)(R12*1), Y12, Y6
	VFMADD231PS 96(AX)(R12*1), Y12, Y7

	LEAQ (AX)(R11*4), AX
	ADDQ $16, BX
	SUBQ $4, CX
	JMP stage3_256_loop4

stage3_256_loop2:
	CMPQ CX, $2
	JL stage3_256_reduce

	VBROADCASTSS 0(BX), Y8
	VBROADCASTSS 4(BX), Y9

	VFMADD231PS 0(AX), Y8, Y0
	VFMADD231PS 32(AX), Y8, Y1
	VFMADD231PS 64(AX), Y8, Y2
	VFMADD231PS 96(AX), Y8, Y3

	VFMADD231PS 0(AX)(R11*1), Y9, Y4
	VFMADD231PS 32(AX)(R11*1), Y9, Y5
	VFMADD231PS 64(AX)(R11*1), Y9, Y6
	VFMADD231PS 96(AX)(R11*1), Y9, Y7

	LEAQ (AX)(R11*2), AX
	ADDQ $8, BX
	SUBQ $2, CX
	JMP stage3_256_loop2

stage3_256_reduce:
	VADDPS Y4, Y0, Y0
	VADDPS Y5, Y1, Y1
	VADDPS Y6, Y2, Y2
	VADDPS Y7, Y3, Y3

stage3_256_rem:
	TESTQ CX, CX
	JLE stage3_256_store

	VBROADCASTSS 0(BX), Y8
	VFMADD231PS 0(AX), Y8, Y0
	VFMADD231PS 32(AX), Y8, Y1
	VFMADD231PS 64(AX), Y8, Y2
	VFMADD231PS 96(AX), Y8, Y3

	ADDQ R11, AX
	ADDQ $4, BX
	DECQ CX
	JMP stage3_256_rem

stage3_256_store:
	VBROADCASTSS X11, Y11
	VMULPS Y11, Y0, Y0
	VMULPS Y11, Y1, Y1
	VMULPS Y11, Y2, Y2
	VMULPS Y11, Y3, Y3
	VMOVUPS Y0, 0(DI)
	VMOVUPS Y1, 32(DI)
	VMOVUPS Y2, 64(DI)
	VMOVUPS Y3, 96(DI)

next256_query:
	MOVQ qByteStride+40(FP), AX
	ADDQ AX, SI
	ADDQ AX, DI
	INCQ R14
	DECQ R13
	JG query256_loop

sdpa256_done:
	VZEROUPPER
	RET

