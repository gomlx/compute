	VEXTRACTF128 $1, Y1, X9
	VEXTRACTF128 $1, Y2, X10
	VEXTRACTF128 $1, Y3, X11
	VADDPS X8, X0, X0
	VADDPS X9, X1, X1
	VADDPS X10, X2, X2
	VADDPS X11, X3, X3

	VUNPCKLPS X1, X0, X8
	VUNPCKHPS X1, X0, X0
	VUNPCKLPS X3, X2, X9
	VUNPCKHPS X3, X2, X2
	VADDPS X0, X8, X0
	VADDPS X2, X9, X2
	VSHUFPS $0x44, X2, X0, X8
	VSHUFPS $0xEE, X2, X0, X0
	VADDPS X0, X8, X0

	TESTQ AX, AX
	JLE qkt1_store4

	VPERMILPS $0x01, X0, X1
	VPERMILPS $0x02, X0, X2
	VPERMILPS $0x03, X0, X3

