	VFMADD231PS 0(R9)(SI*1), Y8, Y0
	VFMADD231PS 0(R10)(SI*1), Y8, Y1
	VFMADD231PS 0(R11)(SI*1), Y8, Y2
	VFMADD231PS 0(DX)(SI*1), Y8, Y3

	ADDQ $32, SI
	SUBQ $8, AX

