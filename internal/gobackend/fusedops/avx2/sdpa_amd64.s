	VMINPS 64(DX), Y2, Y2

	VMOVAPS Y14, Y3
	VFMADD231PS 96(DX), Y2, Y3
	VSUBPS Y14, Y3, Y4
	VPSLLD $23, Y3, Y3
	VPADDD Y15, Y3, Y3

	VFNMADD231PS 160(DX), Y4, Y2
	VFNMADD231PS 192(DX), Y4, Y2

	VMULPS Y2, Y2, Y4
	VMOVUPS 256(DX), Y5
	VFMADD231PS 224(DX), Y2, Y5
	VMOVUPS 320(DX), Y6
	VFMADD231PS 288(DX), Y2, Y6
	VMOVUPS 384(DX), Y7
	VFMADD231PS 352(DX), Y2, Y7
	VADDPS Y15, Y2, Y8
	VMULPS Y4, Y4, Y9
	VFMADD213PS Y6, Y4, Y5
	VFMADD213PS Y8, Y4, Y7
	VFMADD213PS Y7, Y9, Y5
	VMULPS Y3, Y5, Y2

	VMOVUPS Y2, (BX)
	VADDPS Y2, Y11, Y11

	ADDQ $32, BX
	SUBQ $8, CX
	JG accum256_stage2_loop8

	VEXTRACTF128 $1, Y11, X12
	VADDPS X12, X11, X11
	VPERMILPS $0xEE, X11, X12
	VADDPS X12, X11, X11
