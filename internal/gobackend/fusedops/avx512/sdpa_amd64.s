	VFMADD231PS Z11, Z19, Z0
	VFMADD231PS Z11, Z23, Z1
	VFMADD231PS Z11, Z27, Z2
	VFMADD231PS Z11, Z31, Z3

	XORQ AX, AX
	JMP qkt4_512_k1_fold_z

// --- Register-pinned headDim == 32 fast path (4 queries in Z16..Z23) ---
qkt4_512_dim32:
