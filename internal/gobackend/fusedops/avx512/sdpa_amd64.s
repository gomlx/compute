	VMOVUPS 64(R8), Z17
	VMOVUPS 0(R9), Z18
	VMOVUPS 64(R9), Z19
	VMOVUPS 0(R10), Z20
	VMOVUPS 64(R10), Z21
	VMOVUPS 0(R11), Z22
	VMOVUPS 64(R11), Z23

qkt4_512_dim32_key2_loop:
	CMPQ CX, $2
	JL qkt4_512_dim32_key1_rem

	LEAQ (R12)(R13*1), DX

	VMOVUPS 0(R12), Z8
	VMOVUPS 64(R12), Z9
	VMOVUPS 0(DX), Z12
	VMOVUPS 64(DX), Z13

	VMULPS Z8, Z16, Z0
	VMULPS Z12, Z16, Z1
	VMULPS Z8, Z18, Z2
	VMULPS Z12, Z18, Z3
	VMULPS Z8, Z20, Z4
	VMULPS Z12, Z20, Z5
	VMULPS Z8, Z22, Z6
	VMULPS Z12, Z22, Z7

