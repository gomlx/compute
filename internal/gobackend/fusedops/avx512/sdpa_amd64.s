// Read-only constants table for AVX-512 SDPA kernels.
// Offsets (in bytes):
//   0:  -Inf         (0xFF800000)
//   4:  vMinLog      (-88.0296936, 0xC2B00F34)
//   8:  vMaxLog      ( 88.0296936, 0x42B00F34)
//   12: vLog2E       (1.4426950408889634, 0x3FB8AA3B)
//   16: vMagic       (12582912.0, 0x4B400000)
//   20: vLn2Hi       (0.693359375, 0x3F318000)
//   24: vLn2Lo       (-2.12194440e-4, 0xB95E8083)
//   28: vP7          (1.9875691500e-4, 0x39506967)
//   32: vP6          (1.3981999507e-3, 0x3AB743CE)
//   36: vP5          (8.3334519073e-3, 0x3C088895)
//   40: vP4          (4.1665795894e-2, 0x3D2AA9C1)
//   44: vP3          (1.6666665459e-1, 0x3E2AAA9F)
//   48: vP2          (5.0000001201e-1, 0x3F000000)
//   52: vOne/Bias127 (1.0f / 127<<23, 0x3F800000)
DATA ·sdpaAVX512Consts+0(SB)/4, $0xFF800000
DATA ·sdpaAVX512Consts+4(SB)/4, $0xC2B00F34
DATA ·sdpaAVX512Consts+8(SB)/4, $0x42B00F34
DATA ·sdpaAVX512Consts+12(SB)/4, $0x3FB8AA3B
DATA ·sdpaAVX512Consts+16(SB)/4, $0x4B400000
DATA ·sdpaAVX512Consts+20(SB)/4, $0x3F318000
DATA ·sdpaAVX512Consts+24(SB)/4, $0xB95E8083
DATA ·sdpaAVX512Consts+28(SB)/4, $0x39506967
DATA ·sdpaAVX512Consts+32(SB)/4, $0x3AB743CE
DATA ·sdpaAVX512Consts+36(SB)/4, $0x3C088895
DATA ·sdpaAVX512Consts+40(SB)/4, $0x3D2AA9C1
DATA ·sdpaAVX512Consts+44(SB)/4, $0x3E2AAA9F
DATA ·sdpaAVX512Consts+48(SB)/4, $0x3F000000
DATA ·sdpaAVX512Consts+52(SB)/4, $0x3F800000
GLOBL ·sdpaAVX512Consts(SB), RODATA|NOPTR, $56

// ============================================================================
// STAGE 1 (4 Query Rows): Q[4, headDim] @ K[blockKVLen, headDim]^T
// ============================================================================
// func sdpaQKT4RowsAVX512Asm(
//     qRow0, qRow1, qRow2, qRow3 unsafe.Pointer,
//     kPtr unsafe.Pointer,
//     kvByteStride, blockKVLen, headDim int,
//     sRow0, sRow1, sRow2, sRow3 unsafe.Pointer,
// )
TEXT ·sdpaQKT4RowsAVX512Asm(SB), NOSPLIT, $0-96
	MOVQ qRow0+0(FP), R8
	MOVQ qRow1+8(FP), R9
	MOVQ qRow2+16(FP), R10
	MOVQ qRow3+24(FP), R11
	MOVQ kPtr+32(FP), R12
	MOVQ kvByteStride+40(FP), R13
	MOVQ blockKVLen+48(FP), CX
	MOVQ headDim+56(FP), BX
	MOVQ sRow0+64(FP), R14
	MOVQ sRow1+72(FP), R15
	MOVQ sRow2+80(FP), DI
	MOVQ sRow3+88(FP), BP

	TESTQ CX, CX
	JLE qkt4_512_done

	// Fast register-pinned path for headDim == 64:
	// All 4 query rows (4 x 64 float32 = 16 ZMMs) stay pinned in Z16..Z31 across the entire key loop.
	CMPQ BX, $64
	JE qkt4_512_dim64

	// Fast register-pinned path for headDim == 32:
	// All 4 query rows (4 x 32 float32 = 8 ZMMs) stay pinned in Z16..Z23 across the entire key loop.
	CMPQ BX, $32
	JE qkt4_512_dim32

qkt4_512_key2_loop:
	CMPQ CX, $2
	JL qkt4_512_key1_rem

	LEAQ (R12)(R13*1), DX // DX = kCol1

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z6, Z6, Z6
	VXORPS Z7, Z7, Z7

	XORQ SI, SI
	MOVQ BX, AX

qkt4_512_d32_loop:
	CMPQ AX, $32
	JL qkt4_512_d16_check

	VMOVUPS 0(R8)(SI*1), Z16
	VMOVUPS 0(R9)(SI*1), Z17
	VMOVUPS 0(R10)(SI*1), Z18
	VMOVUPS 0(R11)(SI*1), Z19
	VMOVUPS 0(R12)(SI*1), Z20
	VMOVUPS 0(DX)(SI*1), Z21

	VFMADD231PS Z20, Z16, Z0
	VFMADD231PS Z21, Z16, Z1
	VFMADD231PS Z20, Z17, Z2
	VFMADD231PS Z21, Z17, Z3
	VFMADD231PS Z20, Z18, Z4
	VFMADD231PS Z21, Z18, Z5
	VFMADD231PS Z20, Z19, Z6
	VFMADD231PS Z21, Z19, Z7

	VMOVUPS 64(R8)(SI*1), Z16
	VMOVUPS 64(R9)(SI*1), Z17
	VMOVUPS 64(R10)(SI*1), Z18
	VMOVUPS 64(R11)(SI*1), Z19
	VMOVUPS 64(R12)(SI*1), Z20
	VMOVUPS 64(DX)(SI*1), Z21

	VFMADD231PS Z20, Z16, Z0
	VFMADD231PS Z21, Z16, Z1
	VFMADD231PS Z20, Z17, Z2
	VFMADD231PS Z21, Z17, Z3
	VFMADD231PS Z20, Z18, Z4
	VFMADD231PS Z21, Z18, Z5
	VFMADD231PS Z20, Z19, Z6
	VFMADD231PS Z21, Z19, Z7

	ADDQ $128, SI
	SUBQ $32, AX
	JMP qkt4_512_d32_loop

qkt4_512_d16_check:
	CMPQ AX, $16
	JL qkt4_512_fold_z_to_y

	VMOVUPS 0(R8)(SI*1), Z16
	VMOVUPS 0(R9)(SI*1), Z17
	VMOVUPS 0(R10)(SI*1), Z18
	VMOVUPS 0(R11)(SI*1), Z19
	VMOVUPS 0(R12)(SI*1), Z20
	VMOVUPS 0(DX)(SI*1), Z21

	VFMADD231PS Z20, Z16, Z0
	VFMADD231PS Z21, Z16, Z1
	VFMADD231PS Z20, Z17, Z2
	VFMADD231PS Z21, Z17, Z3
	VFMADD231PS Z20, Z18, Z4
	VFMADD231PS Z21, Z18, Z5
	VFMADD231PS Z20, Z19, Z6
	VFMADD231PS Z21, Z19, Z7

	ADDQ $64, SI
	SUBQ $16, AX

qkt4_512_fold_z_to_y:
	// Fold 512-bit Z0..Z7 -> 256-bit Y0..Y7
	VEXTRACTF32X8 $1, Z0, Y8
	VEXTRACTF32X8 $1, Z1, Y9
	VEXTRACTF32X8 $1, Z2, Y10
	VEXTRACTF32X8 $1, Z3, Y11
	VADDPS Y8, Y0, Y0
	VADDPS Y9, Y1, Y1
	VADDPS Y10, Y2, Y2
	VADDPS Y11, Y3, Y3

	VEXTRACTF32X8 $1, Z4, Y8
	VEXTRACTF32X8 $1, Z5, Y9
	VEXTRACTF32X8 $1, Z6, Y10
	VEXTRACTF32X8 $1, Z7, Y11
	VADDPS Y8, Y4, Y4
	VADDPS Y9, Y5, Y5
	VADDPS Y10, Y6, Y6
	VADDPS Y11, Y7, Y7

	CMPQ AX, $8
	JL qkt4_512_reduce_pairs

	VMOVUPS 0(R8)(SI*1), Y8
	VMOVUPS 0(R9)(SI*1), Y9
	VMOVUPS 0(R10)(SI*1), Y10
	VMOVUPS 0(R11)(SI*1), Y11
	VMOVUPS 0(R12)(SI*1), Y12
	VMOVUPS 0(DX)(SI*1), Y13

	VFMADD231PS Y12, Y8, Y0
	VFMADD231PS Y13, Y8, Y1
	VFMADD231PS Y12, Y9, Y2
	VFMADD231PS Y13, Y9, Y3
	VFMADD231PS Y12, Y10, Y4
	VFMADD231PS Y13, Y10, Y5
	VFMADD231PS Y12, Y11, Y6
	VFMADD231PS Y13, Y11, Y7

	ADDQ $32, SI
	SUBQ $8, AX

qkt4_512_reduce_pairs:
	// Reduce (Y0, Y1) -> X0[0..1], (Y2, Y3) -> X2[0..1], (Y4, Y5) -> X4[0..1], (Y6, Y7) -> X6[0..1]
	VEXTRACTF128 $1, Y0, X8
	VEXTRACTF128 $1, Y1, X9
	VADDPS X8, X0, X0
	VADDPS X9, X1, X1
	VUNPCKLPS X1, X0, X8
	VUNPCKHPS X1, X0, X0
	VADDPS X0, X8, X0
	VPERMILPS $0xEE, X0, X8
	VADDPS X8, X0, X0

	VEXTRACTF128 $1, Y2, X8
	VEXTRACTF128 $1, Y3, X9
	VADDPS X8, X2, X2
	VADDPS X9, X3, X3
	VUNPCKLPS X3, X2, X8
	VUNPCKHPS X3, X2, X2
	VADDPS X2, X8, X2
	VPERMILPS $0xEE, X2, X8
	VADDPS X8, X2, X2

	VEXTRACTF128 $1, Y4, X8
	VEXTRACTF128 $1, Y5, X9
	VADDPS X8, X4, X4
	VADDPS X9, X5, X5
	VUNPCKLPS X5, X4, X8
	VUNPCKHPS X5, X4, X4
	VADDPS X4, X8, X4
	VPERMILPS $0xEE, X4, X8
	VADDPS X8, X4, X4

	VEXTRACTF128 $1, Y6, X8
	VEXTRACTF128 $1, Y7, X9
	VADDPS X8, X6, X6
	VADDPS X9, X7, X7
	VUNPCKLPS X7, X6, X8
	VUNPCKHPS X7, X6, X6
	VADDPS X6, X8, X6
	VPERMILPS $0xEE, X6, X8
	VADDPS X8, X6, X6

	TESTQ AX, AX
	JLE qkt4_512_store_pairs

qkt4_512_d1_loop:
	VBROADCASTSS 0(R8)(SI*1), X8
	VBROADCASTSS 0(R9)(SI*1), X9
	VBROADCASTSS 0(R10)(SI*1), X10
	VBROADCASTSS 0(R11)(SI*1), X11

	VMOVSS 0(R12)(SI*1), X12
	VINSERTPS $0x10, 0(DX)(SI*1), X12, X12

	VFMADD231PS X12, X8, X0
	VFMADD231PS X12, X9, X2
	VFMADD231PS X12, X10, X4
	VFMADD231PS X12, X11, X6

	ADDQ $4, SI
	DECQ AX
	JNZ qkt4_512_d1_loop

qkt4_512_store_pairs:
	VMOVSD X0, (R14)
	VMOVSD X2, (R15)
	VMOVSD X4, (DI)
	VMOVSD X6, (BP)

	LEAQ (R12)(R13*2), R12
	ADDQ $8, R14
	ADDQ $8, R15
	ADDQ $8, DI
	ADDQ $8, BP
	SUBQ $2, CX
	JMP qkt4_512_key2_loop

qkt4_512_key1_rem:
	TESTQ CX, CX
	JLE qkt4_512_done

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3

	XORQ SI, SI
	MOVQ BX, AX

qkt4_512_k1_d16_loop:
	CMPQ AX, $16
	JL qkt4_512_k1_fold_z

	VMOVUPS 0(R8)(SI*1), Z16
	VMOVUPS 0(R9)(SI*1), Z17
	VMOVUPS 0(R10)(SI*1), Z18
	VMOVUPS 0(R11)(SI*1), Z19
	VMOVUPS 0(R12)(SI*1), Z20

	VFMADD231PS Z20, Z16, Z0
	VFMADD231PS Z20, Z17, Z1
	VFMADD231PS Z20, Z18, Z2
	VFMADD231PS Z20, Z19, Z3

	ADDQ $64, SI
	SUBQ $16, AX
	JMP qkt4_512_k1_d16_loop

qkt4_512_k1_fold_z:
	VEXTRACTF32X8 $1, Z0, Y8
	VEXTRACTF32X8 $1, Z1, Y9
	VEXTRACTF32X8 $1, Z2, Y10
	VEXTRACTF32X8 $1, Z3, Y11
	VADDPS Y8, Y0, Y0
	VADDPS Y9, Y1, Y1
	VADDPS Y10, Y2, Y2
	VADDPS Y11, Y3, Y3

	CMPQ AX, $8
	JL qkt4_512_k1_reduce

	VMOVUPS 0(R8)(SI*1), Y8
	VMOVUPS 0(R9)(SI*1), Y9
	VMOVUPS 0(R10)(SI*1), Y10
	VMOVUPS 0(R11)(SI*1), Y11
	VMOVUPS 0(R12)(SI*1), Y12

	VFMADD231PS Y12, Y8, Y0
	VFMADD231PS Y12, Y9, Y1
	VFMADD231PS Y12, Y10, Y2
	VFMADD231PS Y12, Y11, Y3

	ADDQ $32, SI
	SUBQ $8, AX

qkt4_512_k1_reduce:
	VEXTRACTF128 $1, Y0, X8
	VEXTRACTF128 $1, Y1, X9
	VEXTRACTF128 $1, Y2, X10
	VEXTRACTF128 $1, Y3, X11
	VADDPS X8, X0, X0
	VADDPS X9, X1, X1
	VADDPS X10, X2, X2
	VADDPS X11, X3, X3

	VUNPCKLPS X1, X0, X8
	VUNPCKHPS X1, X0, X0
	VUNPCKLPS X3, X2, X9
	VUNPCKHPS X3, X2, X2
	VADDPS X0, X8, X0
	VADDPS X2, X9, X2
	VSHUFPS $0x44, X2, X0, X8
	VSHUFPS $0xEE, X2, X0, X0
	VADDPS X0, X8, X0

	VPERMILPS $0x01, X0, X1
	VPERMILPS $0x02, X0, X2
	VPERMILPS $0x03, X0, X3

	TESTQ AX, AX
	JLE qkt4_512_k1_store

qkt4_512_k1_d1_loop:
	VMOVSS 0(R8)(SI*1), X8
	VMOVSS 0(R9)(SI*1), X9
	VMOVSS 0(R10)(SI*1), X10
	VMOVSS 0(R11)(SI*1), X11
	VMOVSS 0(R12)(SI*1), X12

	VFMADD231SS X12, X8, X0
	VFMADD231SS X12, X9, X1
	VFMADD231SS X12, X10, X2
	VFMADD231SS X12, X11, X3

	ADDQ $4, SI
	DECQ AX
	JNZ qkt4_512_k1_d1_loop

qkt4_512_k1_store:
	VMOVSS X0, (R14)
	VMOVSS X1, (R15)
	VMOVSS X2, (DI)
	VMOVSS X3, (BP)
	VZEROUPPER
	RET

// --- Register-pinned headDim == 64 fast path (4 queries in Z16..Z31) ---
qkt4_512_dim64:
	VMOVUPS 0(R8), Z16
	VMOVUPS 64(R8), Z17
	VMOVUPS 128(R8), Z18
	VMOVUPS 192(R8), Z19

	VMOVUPS 0(R9), Z20
	VMOVUPS 64(R9), Z21
	VMOVUPS 128(R9), Z22
	VMOVUPS 192(R9), Z23

	VMOVUPS 0(R10), Z24
	VMOVUPS 64(R10), Z25
	VMOVUPS 128(R10), Z26
	VMOVUPS 192(R10), Z27

	VMOVUPS 0(R11), Z28
	VMOVUPS 64(R11), Z29
	VMOVUPS 128(R11), Z30
	VMOVUPS 192(R11), Z31

qkt4_512_dim64_key2_loop:
	CMPQ CX, $2
	JL qkt4_512_dim64_key1_rem

	LEAQ (R12)(R13*1), DX

	VMOVUPS 0(R12), Z8
	VMOVUPS 64(R12), Z9
	VMOVUPS 128(R12), Z10
	VMOVUPS 192(R12), Z11

	VMOVUPS 0(DX), Z12
	VMOVUPS 64(DX), Z13
	VMOVUPS 128(DX), Z14
	VMOVUPS 192(DX), Z15

	VMULPS Z8, Z16, Z0
	VMULPS Z12, Z16, Z1
	VMULPS Z8, Z20, Z2
	VMULPS Z12, Z20, Z3
	VMULPS Z8, Z24, Z4
	VMULPS Z12, Z24, Z5
	VMULPS Z8, Z28, Z6
	VMULPS Z12, Z28, Z7

	VFMADD231PS Z9, Z17, Z0
	VFMADD231PS Z13, Z17, Z1
	VFMADD231PS Z9, Z21, Z2
	VFMADD231PS Z13, Z21, Z3
	VFMADD231PS Z9, Z25, Z4
	VFMADD231PS Z13, Z25, Z5
	VFMADD231PS Z9, Z29, Z6
	VFMADD231PS Z13, Z29, Z7

	VFMADD231PS Z10, Z18, Z0
	VFMADD231PS Z14, Z18, Z1
	VFMADD231PS Z10, Z22, Z2
	VFMADD231PS Z14, Z22, Z3
	VFMADD231PS Z10, Z26, Z4
	VFMADD231PS Z14, Z26, Z5
	VFMADD231PS Z10, Z30, Z6
	VFMADD231PS Z14, Z30, Z7

	VFMADD231PS Z11, Z19, Z0
	VFMADD231PS Z15, Z19, Z1
	VFMADD231PS Z11, Z23, Z2
	VFMADD231PS Z15, Z23, Z3
	VFMADD231PS Z11, Z27, Z4
	VFMADD231PS Z15, Z27, Z5
	VFMADD231PS Z11, Z31, Z6
	VFMADD231PS Z15, Z31, Z7

	// Fold Z0..Z7 -> Y0..Y7 -> X0, X2, X4, X6
	VEXTRACTF32X8 $1, Z0, Y8
	VEXTRACTF32X8 $1, Z1, Y9
	VEXTRACTF32X8 $1, Z2, Y10
	VEXTRACTF32X8 $1, Z3, Y11
	VADDPS Y8, Y0, Y0
	VADDPS Y9, Y1, Y1
	VADDPS Y10, Y2, Y2
	VADDPS Y11, Y3, Y3

	VEXTRACTF32X8 $1, Z4, Y8
	VEXTRACTF32X8 $1, Z5, Y9
	VEXTRACTF32X8 $1, Z6, Y10
	VEXTRACTF32X8 $1, Z7, Y11
	VADDPS Y8, Y4, Y4
	VADDPS Y9, Y5, Y5
	VADDPS Y10, Y6, Y6
	VADDPS Y11, Y7, Y7

	VEXTRACTF128 $1, Y0, X8
	VEXTRACTF128 $1, Y1, X9
	VADDPS X8, X0, X0
	VADDPS X9, X1, X1
	VUNPCKLPS X1, X0, X8
	VUNPCKHPS X1, X0, X0
	VADDPS X0, X8, X0
	VPERMILPS $0xEE, X0, X8
	VADDPS X8, X0, X0

	VEXTRACTF128 $1, Y2, X8
	VEXTRACTF128 $1, Y3, X9
	VADDPS X8, X2, X2
	VADDPS X9, X3, X3
	VUNPCKLPS X3, X2, X8
	VUNPCKHPS X3, X2, X2
	VADDPS X2, X8, X2
	VPERMILPS $0xEE, X2, X8
	VADDPS X8, X2, X2

	VEXTRACTF128 $1, Y4, X8
	VEXTRACTF128 $1, Y5, X9
	VADDPS X8, X4, X4
	VADDPS X9, X5, X5
	VUNPCKLPS X5, X4, X8
	VUNPCKHPS X5, X4, X4
	VADDPS X4, X8, X4
	VPERMILPS $0xEE, X4, X8
	VADDPS X8, X4, X4

	VEXTRACTF128 $1, Y6, X8
	VEXTRACTF128 $1, Y7, X9
	VADDPS X8, X6, X6
	VADDPS X9, X7, X7
	VUNPCKLPS X7, X6, X8
	VUNPCKHPS X7, X6, X6
	VADDPS X6, X8, X6
	VPERMILPS $0xEE, X6, X8
	VADDPS X8, X6, X6

	VMOVSD X0, (R14)
	VMOVSD X2, (R15)
	VMOVSD X4, (DI)
	VMOVSD X6, (BP)

	LEAQ (R12)(R13*2), R12
	ADDQ $8, R14
	ADDQ $8, R15
	ADDQ $8, DI
	ADDQ $8, BP
	SUBQ $2, CX
	JMP qkt4_512_dim64_key2_loop

qkt4_512_dim64_key1_rem:
	TESTQ CX, CX
	JLE qkt4_512_done

	VMOVUPS 0(R12), Z8
	VMOVUPS 64(R12), Z9
	VMOVUPS 128(R12), Z10
	VMOVUPS 192(R12), Z11

	VMULPS Z8, Z16, Z0
	VMULPS Z8, Z20, Z1
	VMULPS Z8, Z24, Z2
	VMULPS Z8, Z28, Z3

	VFMADD231PS Z9, Z17, Z0
	VFMADD231PS Z9, Z21, Z1
	VFMADD231PS Z9, Z25, Z2
	VFMADD231PS Z9, Z29, Z3

	VFMADD231PS Z10, Z18, Z0
	VFMADD231PS Z10, Z22, Z1
	VFMADD231PS Z10, Z26, Z2
