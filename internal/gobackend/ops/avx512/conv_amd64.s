	VMOVUPS Z6, (R8)
	VMOVUPS Z7, 64(R8)
	VZEROUPPER
	RET


// ===========================================================================
// 3. ConvKernelGradAVX512_8x32Float32Asm: 8x32 Outer-Product Kernel Gradient
// ===========================================================================
// Accumulates an 8x32 tile of gradKernel[ky, kx, cIn:cIn+8, cOut:cOut+32]
// across (batchSize, numY, numX) directly in Z0..Z15.
//
// func ConvKernelGradAVX512_8x32Float32Asm(
//     xBase, vBase, outPtr unsafe.Pointer,
//     batchSize, numY, numX int,
//     xBatchStride, vBatchStride, xYStride, vYStride, xStep, vStep, outRowStrideBytes int)
TEXT ·ConvKernelGradAVX512_8x32Float32Asm(SB), NOSPLIT, $0-104
	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z6, Z6, Z6
	VXORPS Z7, Z7, Z7
	VXORPS Z8, Z8, Z8
	VXORPS Z9, Z9, Z9
	VXORPS Z10, Z10, Z10
	VXORPS Z11, Z11, Z11
	VXORPS Z12, Z12, Z12
	VXORPS Z13, Z13, Z13
	VXORPS Z14, Z14, Z14
	VXORPS Z15, Z15, Z15

	MOVQ batchSize+24(FP), R10
	TESTQ R10, R10
	JLE kgrad_avx512_8x32_store

	MOVQ numY+32(FP), DX
	TESTQ DX, DX
	JLE kgrad_avx512_8x32_store

	MOVQ numX+40(FP), CX
	TESTQ CX, CX
	JLE kgrad_avx512_8x32_store

	MOVQ xBase+0(FP), R8
	MOVQ vBase+8(FP), R9
	MOVQ xStep+80(FP), R11
	MOVQ vStep+88(FP), R12

kgrad_avx512_8x32_b_loop:
	MOVQ numY+32(FP), R13
	MOVQ R8, AX
	MOVQ R9, BX

kgrad_avx512_8x32_y_loop:
	MOVQ numX+40(FP), CX
	MOVQ AX, SI
	MOVQ BX, DI

	CMPQ CX, $2
	JL kgrad_avx512_8x32_x_rem

	PCALIGN $64
kgrad_avx512_8x32_x_loop2:
	VMOVUPS (DI), Z16
	VMOVUPS 64(DI), Z17
	ADDQ R12, DI

	VBROADCASTSS 0(SI), Z18
	VBROADCASTSS 4(SI), Z19
	VBROADCASTSS 8(SI), Z20
	VBROADCASTSS 12(SI), Z21
	VBROADCASTSS 16(SI), Z22
	VBROADCASTSS 20(SI), Z23
	VBROADCASTSS 24(SI), Z24
	VBROADCASTSS 28(SI), Z25
	ADDQ R11, SI

	// Pixel 0 FMAs interleaved with Pixel 1 loads
	VFMADD231PS Z16, Z18, Z0
	VMOVUPS (DI), Z26
	VFMADD231PS Z17, Z18, Z1
	VBROADCASTSS 0(SI), Z18

	VFMADD231PS Z16, Z19, Z2
	VMOVUPS 64(DI), Z27
	VFMADD231PS Z17, Z19, Z3
	VBROADCASTSS 4(SI), Z19

	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VBROADCASTSS 8(SI), Z20

	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VBROADCASTSS 12(SI), Z21

	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9
	VBROADCASTSS 16(SI), Z22

	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11
	VBROADCASTSS 20(SI), Z23

	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13
	VBROADCASTSS 24(SI), Z24

	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15
	VBROADCASTSS 28(SI), Z25

	ADDQ R12, DI
	ADDQ R11, SI

	// Pixel 1 FMAs
	VFMADD231PS Z26, Z18, Z0
	VFMADD231PS Z27, Z18, Z1
	VFMADD231PS Z26, Z19, Z2
	VFMADD231PS Z27, Z19, Z3
	VFMADD231PS Z26, Z20, Z4
	VFMADD231PS Z27, Z20, Z5
	VFMADD231PS Z26, Z21, Z6
	VFMADD231PS Z27, Z21, Z7
	VFMADD231PS Z26, Z22, Z8
	VFMADD231PS Z27, Z22, Z9
	VFMADD231PS Z26, Z23, Z10
	VFMADD231PS Z27, Z23, Z11
	VFMADD231PS Z26, Z24, Z12
	VFMADD231PS Z27, Z24, Z13
	VFMADD231PS Z26, Z25, Z14
	VFMADD231PS Z27, Z25, Z15

	SUBQ $2, CX
	CMPQ CX, $2
	JGE kgrad_avx512_8x32_x_loop2

kgrad_avx512_8x32_x_rem:
	TESTQ CX, CX
	JZ kgrad_avx512_8x32_next_y

	VMOVUPS (DI), Z16
	VMOVUPS 64(DI), Z17
	VBROADCASTSS 0(SI), Z18
	VBROADCASTSS 4(SI), Z19
	VBROADCASTSS 8(SI), Z20
	VBROADCASTSS 12(SI), Z21
	VBROADCASTSS 16(SI), Z22
	VBROADCASTSS 20(SI), Z23
	VBROADCASTSS 24(SI), Z24
	VBROADCASTSS 28(SI), Z25

	VFMADD231PS Z16, Z18, Z0
	VFMADD231PS Z17, Z18, Z1
	VFMADD231PS Z16, Z19, Z2
	VFMADD231PS Z17, Z19, Z3
	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9
	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11
	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13
	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15

kgrad_avx512_8x32_next_y:
	ADDQ xYStride+64(FP), AX
	ADDQ vYStride+72(FP), BX
	DECQ R13
	JNZ kgrad_avx512_8x32_y_loop

	ADDQ xBatchStride+48(FP), R8
	ADDQ vBatchStride+56(FP), R9
	DECQ R10
	JNZ kgrad_avx512_8x32_b_loop

kgrad_avx512_8x32_store:
	MOVQ outPtr+16(FP), DX
	MOVQ outRowStrideBytes+96(FP), R10

	VMOVUPS Z0, (DX)
	VMOVUPS Z1, 64(DX)
	ADDQ R10, DX
	VMOVUPS Z2, (DX)
	VMOVUPS Z3, 64(DX)
	ADDQ R10, DX
	VMOVUPS Z4, (DX)
	VMOVUPS Z5, 64(DX)
	ADDQ R10, DX
	VMOVUPS Z6, (DX)
	VMOVUPS Z7, 64(DX)
	ADDQ R10, DX
	VMOVUPS Z8, (DX)
	VMOVUPS Z9, 64(DX)
	ADDQ R10, DX
	VMOVUPS Z10, (DX)
	VMOVUPS Z11, 64(DX)
