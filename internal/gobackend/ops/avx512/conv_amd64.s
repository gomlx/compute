// ===========================================================================
// 1. ConvAVX512Kernel8x32Float32Asm: Direct 8x32 AVX-512 Convolution Microkernel
// ===========================================================================
// Multiplies 8 rows of LHS ([8, K] with row stride lhsRowStrideBytes) by a
// 32-column panel of packed RHS ([K, 32] with step stride rhsStepBytes) and
// writes the 8x32 tile to outPtr (with row stride outRowStrideBytes).
// Reads directly from the 8 LHS rows via VBROADCASTSS, requiring zero LHS
// transposition or packing.
//
// func ConvAVX512Kernel8x32Float32Asm(
//     lhsPtr, rhsPtr, outPtr unsafe.Pointer,
//     K, lhsRowStrideBytes, rhsStepBytes, outRowStrideBytes int)
TEXT ·ConvAVX512Kernel8x32Float32Asm(SB), NOSPLIT, $0-56
	MOVQ lhsPtr+0(FP), SI                // SI = LHS row 0
	MOVQ rhsPtr+8(FP), DI                // DI = RHS panel pointer
	MOVQ outPtr+16(FP), R8               // R8 = output pointer
	MOVQ K+24(FP), CX                    // CX = K
	MOVQ lhsRowStrideBytes+32(FP), DX    // DX = lhsRowStrideBytes
	MOVQ rhsStepBytes+40(FP), R9         // R9 = rhsStepBytes
	MOVQ outRowStrideBytes+48(FP), R10   // R10 = outRowStrideBytes

	// Zero 16 ZMM accumulators (8 rows x 32 cols)
	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z6, Z6, Z6
	VXORPS Z7, Z7, Z7
	VXORPS Z8, Z8, Z8
	VXORPS Z9, Z9, Z9
	VXORPS Z10, Z10, Z10
	VXORPS Z11, Z11, Z11
	VXORPS Z12, Z12, Z12
	VXORPS Z13, Z13, Z13
	VXORPS Z14, Z14, Z14
	VXORPS Z15, Z15, Z15

	// Set up even-row pointers for rows 2, 4, 6 (odd rows addressed via +(DX*1))
	LEAQ (SI)(DX*2), R11                 // R11 = LHS row 2
	LEAQ (R11)(DX*2), R12                // R12 = LHS row 4
	LEAQ (R12)(DX*2), R13                // R13 = LHS row 6

	TESTQ CX, CX
	JLE conv_avx512_8x32_store

	MOVQ CX, AX
	SHRQ $1, AX                          // AX = K / 2 pairs
	JZ conv_avx512_8x32_odd

	// Prime Buffer A for step 0
	VMOVUPS (DI), Z16
	VMOVUPS 64(DI), Z17
	VBROADCASTSS 0(SI), Z18
	VBROADCASTSS (0)(SI)(DX*1), Z19
	VBROADCASTSS 0(R11), Z20
	VBROADCASTSS (0)(R11)(DX*1), Z21
	VBROADCASTSS 0(R12), Z22
	VBROADCASTSS (0)(R12)(DX*1), Z23
	VBROADCASTSS 0(R13), Z24
	VBROADCASTSS (0)(R13)(DX*1), Z25
	ADDQ R9, DI

	DECQ AX
	JZ conv_avx512_8x32_last_pair

	PCALIGN $64
conv_avx512_8x32_pair_loop:
	// Step A: FMAs using Buffer A (Z16, Z17) while loading Buffer B (Z26, Z27, Z18..Z25)
	VFMADD231PS Z16, Z18, Z0
	VMOVUPS (DI), Z26
	VFMADD231PS Z17, Z18, Z1
	VBROADCASTSS 4(SI), Z18

	VFMADD231PS Z16, Z19, Z2
	VMOVUPS 64(DI), Z27
	VFMADD231PS Z17, Z19, Z3
	VBROADCASTSS (4)(SI)(DX*1), Z19

	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VBROADCASTSS 4(R11), Z20

	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VBROADCASTSS (4)(R11)(DX*1), Z21

	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9
	VBROADCASTSS 4(R12), Z22

	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11
	VBROADCASTSS (4)(R12)(DX*1), Z23

	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13
	VBROADCASTSS 4(R13), Z24

	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15
	VBROADCASTSS (4)(R13)(DX*1), Z25

	ADDQ $8, SI
	ADDQ $8, R11
	ADDQ $8, R12
	ADDQ $8, R13
	ADDQ R9, DI

	// Step B: FMAs using Buffer B (Z26, Z27) while loading next Buffer A (Z16, Z17, Z18..Z25)
	VFMADD231PS Z26, Z18, Z0
	VMOVUPS (DI), Z16
	VFMADD231PS Z27, Z18, Z1
	VBROADCASTSS 0(SI), Z18

	VFMADD231PS Z26, Z19, Z2
	VMOVUPS 64(DI), Z17
	VFMADD231PS Z27, Z19, Z3
	VBROADCASTSS (0)(SI)(DX*1), Z19

	VFMADD231PS Z26, Z20, Z4
	VFMADD231PS Z27, Z20, Z5
	VBROADCASTSS 0(R11), Z20

	VFMADD231PS Z26, Z21, Z6
	VFMADD231PS Z27, Z21, Z7
	VBROADCASTSS (0)(R11)(DX*1), Z21

	VFMADD231PS Z26, Z22, Z8
	VFMADD231PS Z27, Z22, Z9
	VBROADCASTSS 0(R12), Z22

	VFMADD231PS Z26, Z23, Z10
	VFMADD231PS Z27, Z23, Z11
	VBROADCASTSS (0)(R12)(DX*1), Z23

	VFMADD231PS Z26, Z24, Z12
	VFMADD231PS Z27, Z24, Z13
	VBROADCASTSS 0(R13), Z24

	VFMADD231PS Z26, Z25, Z14
	VFMADD231PS Z27, Z25, Z15
	VBROADCASTSS (0)(R13)(DX*1), Z25

	ADDQ R9, DI

	DECQ AX
	JNZ conv_avx512_8x32_pair_loop

conv_avx512_8x32_last_pair:
	// Step A: FMAs using Buffer A (Z16, Z17) while loading Buffer B (Z26, Z27, Z18..Z25)
	VFMADD231PS Z16, Z18, Z0
	VMOVUPS (DI), Z26
	VFMADD231PS Z17, Z18, Z1
	VBROADCASTSS 4(SI), Z18

	VFMADD231PS Z16, Z19, Z2
	VMOVUPS 64(DI), Z27
	VFMADD231PS Z17, Z19, Z3
	VBROADCASTSS (4)(SI)(DX*1), Z19

	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VBROADCASTSS 4(R11), Z20

	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VBROADCASTSS (4)(R11)(DX*1), Z21

	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9
	VBROADCASTSS 4(R12), Z22

	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11
	VBROADCASTSS (4)(R12)(DX*1), Z23

	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13
	VBROADCASTSS 4(R13), Z24

	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15
	VBROADCASTSS (4)(R13)(DX*1), Z25

	ADDQ $8, SI
	ADDQ $8, R11
	ADDQ $8, R12
	ADDQ $8, R13
	ADDQ R9, DI

	// Step B: Pure FMAs using Buffer B (Z26, Z27)
	VFMADD231PS Z26, Z18, Z0
	VFMADD231PS Z27, Z18, Z1
	VFMADD231PS Z26, Z19, Z2
	VFMADD231PS Z27, Z19, Z3
	VFMADD231PS Z26, Z20, Z4
	VFMADD231PS Z27, Z20, Z5
	VFMADD231PS Z26, Z21, Z6
	VFMADD231PS Z27, Z21, Z7
	VFMADD231PS Z26, Z22, Z8
	VFMADD231PS Z27, Z22, Z9
	VFMADD231PS Z26, Z23, Z10
	VFMADD231PS Z27, Z23, Z11
	VFMADD231PS Z26, Z24, Z12
	VFMADD231PS Z27, Z24, Z13
	VFMADD231PS Z26, Z25, Z14
	VFMADD231PS Z27, Z25, Z15

conv_avx512_8x32_odd:
	TESTQ $1, CX
	JZ conv_avx512_8x32_store

	VMOVUPS (DI), Z16
	VMOVUPS 64(DI), Z17
	VBROADCASTSS 0(SI), Z18
	VBROADCASTSS (0)(SI)(DX*1), Z19
	VBROADCASTSS 0(R11), Z20
	VBROADCASTSS (0)(R11)(DX*1), Z21
	VBROADCASTSS 0(R12), Z22
	VBROADCASTSS (0)(R12)(DX*1), Z23
	VBROADCASTSS 0(R13), Z24
	VBROADCASTSS (0)(R13)(DX*1), Z25

	VFMADD231PS Z16, Z18, Z0
	VFMADD231PS Z17, Z18, Z1
	VFMADD231PS Z16, Z19, Z2
	VFMADD231PS Z17, Z19, Z3
	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9
	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11
	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13
	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15

conv_avx512_8x32_store:
	VMOVUPS Z0, (R8)
	VMOVUPS Z1, 64(R8)
	ADDQ R10, R8
	VMOVUPS Z2, (R8)
	VMOVUPS Z3, 64(R8)
	ADDQ R10, R8
	VMOVUPS Z4, (R8)
	VMOVUPS Z5, 64(R8)
	ADDQ R10, R8
	VMOVUPS Z6, (R8)
	VMOVUPS Z7, 64(R8)
	ADDQ R10, R8
	VMOVUPS Z8, (R8)
	VMOVUPS Z9, 64(R8)
	ADDQ R10, R8
	VMOVUPS Z10, (R8)
	VMOVUPS Z11, 64(R8)
	ADDQ R10, R8
	VMOVUPS Z12, (R8)
	VMOVUPS Z13, 64(R8)
	ADDQ R10, R8
	VMOVUPS Z14, (R8)
	VMOVUPS Z15, 64(R8)
	VZEROUPPER
	RET


// ===========================================================================
// 2. ConvAVX512Kernel4x32Float32Asm: Direct 4x32 AVX-512 Convolution Microkernel
// ===========================================================================
// func ConvAVX512Kernel4x32Float32Asm(
//     lhsPtr, rhsPtr, outPtr unsafe.Pointer,
//     K, lhsRowStrideBytes, rhsStepBytes, outRowStrideBytes int)
TEXT ·ConvAVX512Kernel4x32Float32Asm(SB), NOSPLIT, $0-56
	MOVQ lhsPtr+0(FP), SI
	MOVQ rhsPtr+8(FP), DI
	MOVQ outPtr+16(FP), R8
	MOVQ K+24(FP), CX
	MOVQ lhsRowStrideBytes+32(FP), DX
	MOVQ rhsStepBytes+40(FP), R9
	MOVQ outRowStrideBytes+48(FP), R10

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z6, Z6, Z6
	VXORPS Z7, Z7, Z7

	LEAQ (SI)(DX*1), R11
	LEAQ (R11)(DX*1), R12
	LEAQ (R12)(DX*1), R13

	TESTQ CX, CX
	JLE conv_avx512_4x32_store

	MOVQ CX, AX
	SHRQ $1, AX
	JZ conv_avx512_4x32_odd

	VMOVUPS (DI), Z16
	VMOVUPS 64(DI), Z17
	VBROADCASTSS 0(SI), Z18
	VBROADCASTSS 0(R11), Z19
	VBROADCASTSS 0(R12), Z20
	VBROADCASTSS 0(R13), Z21
	ADDQ R9, DI

	DECQ AX
	JZ conv_avx512_4x32_last_pair

	PCALIGN $64
conv_avx512_4x32_pair_loop:
	VFMADD231PS Z16, Z18, Z0
	VMOVUPS (DI), Z26
	VFMADD231PS Z17, Z18, Z1
	VBROADCASTSS 4(SI), Z18

	VFMADD231PS Z16, Z19, Z2
	VMOVUPS 64(DI), Z27
	VFMADD231PS Z17, Z19, Z3
	VBROADCASTSS 4(R11), Z19

	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VBROADCASTSS 4(R12), Z20

	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VBROADCASTSS 4(R13), Z21

	ADDQ $8, SI
	ADDQ $8, R11
	ADDQ $8, R12
	ADDQ $8, R13
	ADDQ R9, DI

	VFMADD231PS Z26, Z18, Z0
	VMOVUPS (DI), Z16
	VFMADD231PS Z27, Z18, Z1
	VBROADCASTSS 0(SI), Z18

	VFMADD231PS Z26, Z19, Z2
	VMOVUPS 64(DI), Z17
	VFMADD231PS Z27, Z19, Z3
	VBROADCASTSS 0(R11), Z19

	VFMADD231PS Z26, Z20, Z4
	VFMADD231PS Z27, Z20, Z5
	VBROADCASTSS 0(R12), Z20

	VFMADD231PS Z26, Z21, Z6
	VFMADD231PS Z27, Z21, Z7
	VBROADCASTSS 0(R13), Z21

	ADDQ R9, DI

	DECQ AX
	JNZ conv_avx512_4x32_pair_loop

conv_avx512_4x32_last_pair:
	VFMADD231PS Z16, Z18, Z0
	VMOVUPS (DI), Z26
	VFMADD231PS Z17, Z18, Z1
	VBROADCASTSS 4(SI), Z18

	VFMADD231PS Z16, Z19, Z2
	VMOVUPS 64(DI), Z27
	VFMADD231PS Z17, Z19, Z3
	VBROADCASTSS 4(R11), Z19

	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VBROADCASTSS 4(R12), Z20

	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VBROADCASTSS 4(R13), Z21

	ADDQ $8, SI
	ADDQ $8, R11
	ADDQ $8, R12
	ADDQ $8, R13
	ADDQ R9, DI

	VFMADD231PS Z26, Z18, Z0
	VFMADD231PS Z27, Z18, Z1
	VFMADD231PS Z26, Z19, Z2
	VFMADD231PS Z27, Z19, Z3
	VFMADD231PS Z26, Z20, Z4
	VFMADD231PS Z27, Z20, Z5
	VFMADD231PS Z26, Z21, Z6
	VFMADD231PS Z27, Z21, Z7

conv_avx512_4x32_odd:
	TESTQ $1, CX
	JZ conv_avx512_4x32_store

	VMOVUPS (DI), Z16
	VMOVUPS 64(DI), Z17
	VBROADCASTSS 0(SI), Z18
	VBROADCASTSS 0(R11), Z19
	VBROADCASTSS 0(R12), Z20
	VBROADCASTSS 0(R13), Z21

	VFMADD231PS Z16, Z18, Z0
	VFMADD231PS Z17, Z18, Z1
	VFMADD231PS Z16, Z19, Z2
	VFMADD231PS Z17, Z19, Z3
	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7

conv_avx512_4x32_store:
