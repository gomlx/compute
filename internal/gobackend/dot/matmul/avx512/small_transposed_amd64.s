#include "textflag.h"

#define REDUCE_Z(z, y, x) \
	VEXTRACTF32X8 $1, z, Y24 \
	VADDPS Y24, y, y \
	VEXTRACTF32X4 $1, y, X24 \
	VADDPS X24, x, x \
	VMOVSHDUP x, X24 \
	VADDPS X24, x, x \
	VPERMILPS $0x02, x, X24 \
	VADDSS X24, x, x

#define REDUCE_Z_F64(z, y, x) \
	VEXTRACTF64X4 $1, z, Y24 \
	VADDPD Y24, y, y \
	VEXTRACTF64X2 $1, y, X24 \
	VADDPD X24, x, x \
	VPERMILPD $0x01, x, X24 \
	VADDSD X24, x, x

