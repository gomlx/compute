TEXT ·avx512SmallNonTransposedTile4x64Float32Asm(SB), NOSPLIT, $0-88
	MOVQ lRow0+0(FP), R8
	MOVQ lRow1+8(FP), R9
	MOVQ lRow2+16(FP), R10
	MOVQ lRow3+24(FP), R11
	MOVQ rhs+32(FP), R12
	MOVQ contractingSize+40(FP), BX
	MOVQ rhsByteStride+48(FP), DX

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z6, Z6, Z6
	VXORPS Z7, Z7, Z7
	VXORPS Z8, Z8, Z8
	VXORPS Z9, Z9, Z9
	VXORPS Z10, Z10, Z10
	VXORPS Z11, Z11, Z11
	VXORPS Z12, Z12, Z12
	VXORPS Z13, Z13, Z13
	VXORPS Z14, Z14, Z14
	VXORPS Z15, Z15, Z15

	TESTQ BX, BX
	JLE write_output_64_f32

	XORQ SI, SI
	XORQ AX, AX

loop_k_64_f32:
	VBROADCASTSS (0)(R8)(SI*1), Z16
	VBROADCASTSS (0)(R9)(SI*1), Z17
	VBROADCASTSS (0)(R10)(SI*1), Z18
	VBROADCASTSS (0)(R11)(SI*1), Z19

	LEAQ (R12)(AX*1), CX
	VMOVUPS 0(CX), Z20
	VMOVUPS 64(CX), Z21
	VMOVUPS 128(CX), Z22
	VMOVUPS 192(CX), Z23

	VFMADD231PS Z20, Z16, Z0
	VFMADD231PS Z21, Z16, Z1
	VFMADD231PS Z22, Z16, Z2
	VFMADD231PS Z23, Z16, Z3

	VFMADD231PS Z20, Z17, Z4
	VFMADD231PS Z21, Z17, Z5
	VFMADD231PS Z22, Z17, Z6
	VFMADD231PS Z23, Z17, Z7

	VFMADD231PS Z20, Z18, Z8
	VFMADD231PS Z21, Z18, Z9
	VFMADD231PS Z22, Z18, Z10
	VFMADD231PS Z23, Z18, Z11

	VFMADD231PS Z20, Z19, Z12
	VFMADD231PS Z21, Z19, Z13
	VFMADD231PS Z22, Z19, Z14
	VFMADD231PS Z23, Z19, Z15

	ADDQ $4, SI
	ADDQ DX, AX
	DECQ BX
	JNZ loop_k_64_f32

write_output_64_f32:
	MOVQ outRow0+56(FP), R13
	MOVQ outRow1+64(FP), R14
	MOVQ outRow2+72(FP), R15
	MOVQ outRow3+80(FP), DI

	VMOVUPS Z0, 0(R13)
	VMOVUPS Z1, 64(R13)
	VMOVUPS Z2, 128(R13)
	VMOVUPS Z3, 192(R13)

	VMOVUPS Z4, 0(R14)
	VMOVUPS Z5, 64(R14)
	VMOVUPS Z6, 128(R14)
	VMOVUPS Z7, 192(R14)

	VMOVUPS Z8, 0(R15)
	VMOVUPS Z9, 64(R15)
	VMOVUPS Z10, 128(R15)
	VMOVUPS Z11, 192(R15)

	VMOVUPS Z12, 0(DI)
	VMOVUPS Z13, 64(DI)
	VMOVUPS Z14, 128(DI)
	VMOVUPS Z15, 192(DI)

	VZEROUPPER
	RET

