#include "textflag.h"

// func avx512LargeKernelFloat16Asm(
//     packedLHS, packedRHS []float16.Float16,
//     packedOutput []float32,
//     lhsPanelRows, rhsPanelCols int,
//     contractingLen int,
//     lhsActiveRows, rhsActiveCols int,
//     accumulate bool)
TEXT ·avx512LargeKernelFloat16Asm(SB), NOSPLIT, $0-120
	MOVQ packedLHS_base+0(FP), R8        // R8 = lhsBasePtr (float16 = 2 bytes)
	MOVQ packedRHS_base+24(FP), R9       // R9 = rhsBasePtr (float16 = 2 bytes)
	MOVQ packedOutput_base+48(FP), R10   // R10 = outBasePtr (float32 = 4 bytes)
	MOVQ rhsPanelCols+80(FP), R11        // R11 = outputStride (cols)
	MOVQ contractingLen+88(FP), R12      // R12 = contractingLen (K)
	MOVQ lhsActiveRows+96(FP), R13       // R13 = lhsActiveRows (M)
	MOVQ rhsActiveCols+104(FP), R14      // R14 = rhsActiveCols (N)
	MOVB accumulate+112(FP), R15         // R15 = accumulate (0 = overwrite, 1 = add)

	SHLQ $2, R11                         // R11 = outputStride in bytes (float32 = 4 bytes)

	XORQ AX, AX                          // AX = lhsRowIdx = 0

loop_lhs_f16:
	CMPQ AX, R13
	JGE done_f16

	XORQ BX, BX                          // BX = rhsColIdx = 0

loop_rhs_f16:
	CMPQ BX, R14
	JGE next_lhs_f16

	// 1. Zero all 16 accumulators (Z0..Z15)
	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z6, Z6, Z6
	VXORPS Z7, Z7, Z7
	VXORPS Z8, Z8, Z8
	VXORPS Z9, Z9, Z9
	VXORPS Z10, Z10, Z10
	VXORPS Z11, Z11, Z11
	VXORPS Z12, Z12, Z12
	VXORPS Z13, Z13, Z13
	VXORPS Z14, Z14, Z14
	VXORPS Z15, Z15, Z15

	// 2. Compute lhsPtr and rhsPtr (float16 = 2 bytes)
	// For 8-row LHS strip: strip has 8 float16s = 16 bytes per step.
	// SI = R8 + (lhsRowIdx * contractingLen * 2)
	MOVQ AX, SI
	IMULQ R12, SI
	SHLQ $1, SI
	ADDQ R8, SI

	// For 32-col RHS strip: strip has 32 float16s = 64 bytes per step.
	// DI = R9 + (rhsColIdx * contractingLen * 2)
	MOVQ BX, DI
	IMULQ R12, DI
	SHLQ $1, DI
	ADDQ R9, DI

	// 3. K-loop with 2-stage ping-pong pipeline (unroll by 2)
	MOVQ R12, CX                         // CX = contractingLen
	TESTQ CX, CX
	JLE store_output_f16

	SHRQ $1, CX                          // CX = pairs = contractingLen / 2
	JZ k_odd_f16

	// Prime Buffer A for Step 0 outside the loop
	// 2 RHS vectors (32 float16s = 64 bytes) converted to float32:
	VCVTPH2PS (DI), Z16
	VCVTPH2PS 32(DI), Z17

	// 8 LHS values (8 float16s = 16 bytes) converted to float32 and broadcast:
	VCVTPH2PS (SI), Y18
	VEXTRACTF32X4 $1, Y18, X22
	VPERMILPS $0x55, X18, X19
	VPERMILPS $0xAA, X18, X20
	VPERMILPS $0xFF, X18, X21
	VBROADCASTSS X18, Z18
	VBROADCASTSS X19, Z19
	VBROADCASTSS X20, Z20
	VBROADCASTSS X21, Z21
	VPERMILPS $0x55, X22, X23
	VPERMILPS $0xAA, X22, X24
	VPERMILPS $0xFF, X22, X25
	VBROADCASTSS X22, Z22
	VBROADCASTSS X23, Z23
	VBROADCASTSS X24, Z24
	VBROADCASTSS X25, Z25

	ADDQ $16, SI
	ADDQ $64, DI

	DECQ CX
	JZ k_last_pair_f16

	PCALIGN $64
k_pair_loop_f16:
	// Step A: FMAs using Buffer A (Z16, Z17, Z18..Z25)
	VFMADD231PS Z16, Z18, Z0
	VCVTPH2PS (DI), Z26
	VFMADD231PS Z17, Z18, Z1
	VCVTPH2PS 32(DI), Z27

	VFMADD231PS Z16, Z19, Z2
	VFMADD231PS Z17, Z19, Z3

	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5

	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7

	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9

	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11

	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13

	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15

	// Load Buffer B LHS (Z18..Z25)
	VCVTPH2PS (SI), Y18
	VEXTRACTF32X4 $1, Y18, X22
	VPERMILPS $0x55, X18, X19
	VPERMILPS $0xAA, X18, X20
	VPERMILPS $0xFF, X18, X21
	VBROADCASTSS X18, Z18
	VBROADCASTSS X19, Z19
	VBROADCASTSS X20, Z20
	VBROADCASTSS X21, Z21
	VPERMILPS $0x55, X22, X23
	VPERMILPS $0xAA, X22, X24
	VPERMILPS $0xFF, X22, X25
	VBROADCASTSS X22, Z22
	VBROADCASTSS X23, Z23
	VBROADCASTSS X24, Z24
	VBROADCASTSS X25, Z25

	ADDQ $16, SI
	ADDQ $64, DI

	// Step B: FMAs using Buffer B (Z26, Z27, Z18..Z25)
	VFMADD231PS Z26, Z18, Z0
	VCVTPH2PS (DI), Z16
	VFMADD231PS Z27, Z18, Z1
	VCVTPH2PS 32(DI), Z17

	VFMADD231PS Z26, Z19, Z2
	VFMADD231PS Z27, Z19, Z3

	VFMADD231PS Z26, Z20, Z4
	VFMADD231PS Z27, Z20, Z5

	VFMADD231PS Z26, Z21, Z6
	VFMADD231PS Z27, Z21, Z7

	VFMADD231PS Z26, Z22, Z8
	VFMADD231PS Z27, Z22, Z9

	VFMADD231PS Z26, Z23, Z10
	VFMADD231PS Z27, Z23, Z11

	VFMADD231PS Z26, Z24, Z12
	VFMADD231PS Z27, Z24, Z13

	VFMADD231PS Z26, Z25, Z14
	VFMADD231PS Z27, Z25, Z15

	// Load Buffer A LHS (Z18..Z25)
	VCVTPH2PS (SI), Y18
	VEXTRACTF32X4 $1, Y18, X22
	VPERMILPS $0x55, X18, X19
	VPERMILPS $0xAA, X18, X20
	VPERMILPS $0xFF, X18, X21
	VBROADCASTSS X18, Z18
	VBROADCASTSS X19, Z19
	VBROADCASTSS X20, Z20
	VBROADCASTSS X21, Z21
	VPERMILPS $0x55, X22, X23
	VPERMILPS $0xAA, X22, X24
	VPERMILPS $0xFF, X22, X25
	VBROADCASTSS X22, Z22
	VBROADCASTSS X23, Z23
	VBROADCASTSS X24, Z24
	VBROADCASTSS X25, Z25

	ADDQ $16, SI
	ADDQ $64, DI

	DECQ CX
	JNZ k_pair_loop_f16

k_last_pair_f16:
	// Last pair: Step A loads Buffer B, then Step B executes without next prefetch
	VFMADD231PS Z16, Z18, Z0
	VCVTPH2PS (DI), Z26
	VFMADD231PS Z17, Z18, Z1
	VCVTPH2PS 32(DI), Z27

	VFMADD231PS Z16, Z19, Z2
	VFMADD231PS Z17, Z19, Z3

	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5

	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7

	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9

	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11

	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13

	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15

	VCVTPH2PS (SI), Y18
	VEXTRACTF32X4 $1, Y18, X22
	VPERMILPS $0x55, X18, X19
	VPERMILPS $0xAA, X18, X20
	VPERMILPS $0xFF, X18, X21
	VBROADCASTSS X18, Z18
	VBROADCASTSS X19, Z19
	VBROADCASTSS X20, Z20
	VBROADCASTSS X21, Z21
	VPERMILPS $0x55, X22, X23
	VPERMILPS $0xAA, X22, X24
	VPERMILPS $0xFF, X22, X25
	VBROADCASTSS X22, Z22
	VBROADCASTSS X23, Z23
	VBROADCASTSS X24, Z24
	VBROADCASTSS X25, Z25

	ADDQ $16, SI
	ADDQ $64, DI

	// Step B without next prefetch
	VFMADD231PS Z26, Z18, Z0
	VFMADD231PS Z27, Z18, Z1
	VFMADD231PS Z26, Z19, Z2
	VFMADD231PS Z27, Z19, Z3
	VFMADD231PS Z26, Z20, Z4
	VFMADD231PS Z27, Z20, Z5
	VFMADD231PS Z26, Z21, Z6
	VFMADD231PS Z27, Z21, Z7
	VFMADD231PS Z26, Z22, Z8
	VFMADD231PS Z27, Z22, Z9
	VFMADD231PS Z26, Z23, Z10
	VFMADD231PS Z27, Z23, Z11
	VFMADD231PS Z26, Z24, Z12
	VFMADD231PS Z27, Z24, Z13
	VFMADD231PS Z26, Z25, Z14
	VFMADD231PS Z27, Z25, Z15

k_odd_f16:
	MOVQ R12, CX
	ANDQ $1, CX
	JZ store_output_f16

	// Odd iteration
	VCVTPH2PS (DI), Z16
	VCVTPH2PS 32(DI), Z17

	VCVTPH2PS (SI), Y18
	VEXTRACTF32X4 $1, Y18, X22
	VPERMILPS $0x55, X18, X19
	VPERMILPS $0xAA, X18, X20
	VPERMILPS $0xFF, X18, X21
	VBROADCASTSS X18, Z18
	VBROADCASTSS X19, Z19
	VBROADCASTSS X20, Z20
	VBROADCASTSS X21, Z21
	VPERMILPS $0x55, X22, X23
	VPERMILPS $0xAA, X22, X24
	VPERMILPS $0xFF, X22, X25
	VBROADCASTSS X22, Z22
	VBROADCASTSS X23, Z23
	VBROADCASTSS X24, Z24
	VBROADCASTSS X25, Z25

	VFMADD231PS Z16, Z18, Z0
	VFMADD231PS Z17, Z18, Z1
	VFMADD231PS Z16, Z19, Z2
	VFMADD231PS Z17, Z19, Z3
	VFMADD231PS Z16, Z20, Z4
	VFMADD231PS Z17, Z20, Z5
	VFMADD231PS Z16, Z21, Z6
	VFMADD231PS Z17, Z21, Z7
	VFMADD231PS Z16, Z22, Z8
	VFMADD231PS Z17, Z22, Z9
	VFMADD231PS Z16, Z23, Z10
	VFMADD231PS Z17, Z23, Z11
	VFMADD231PS Z16, Z24, Z12
	VFMADD231PS Z17, Z24, Z13
	VFMADD231PS Z16, Z25, Z14
	VFMADD231PS Z17, Z25, Z15

store_output_f16:
	// Compute outPtr = R10 + (lhsRowIdx * outputStrideBytes) + (rhsColIdx * 4)
	MOVQ AX, DX
	IMULQ R11, DX                        // R11 is already in bytes
	MOVQ BX, SI
	SHLQ $2, SI                          // Float32 output is 4 bytes
	ADDQ SI, DX
	ADDQ R10, DX                         // DX = outPtr for Row 0

	TESTB R15, R15
	JNZ store_output_f16_accum

	// Overwrite:
	// Row 0
	VMOVDQU32 Z0, (DX)
	VMOVDQU32 Z1, 64(DX)

	// Row 1
	ADDQ R11, DX
	VMOVDQU32 Z2, (DX)
	VMOVDQU32 Z3, 64(DX)

	// Row 2
	ADDQ R11, DX
	VMOVDQU32 Z4, (DX)
	VMOVDQU32 Z5, 64(DX)

	// Row 3
	ADDQ R11, DX
	VMOVDQU32 Z6, (DX)
	VMOVDQU32 Z7, 64(DX)

	// Row 4
	ADDQ R11, DX
	VMOVDQU32 Z8, (DX)
	VMOVDQU32 Z9, 64(DX)

	// Row 5
	ADDQ R11, DX
	VMOVDQU32 Z10, (DX)
	VMOVDQU32 Z11, 64(DX)

	// Row 6
	ADDQ R11, DX
	VMOVDQU32 Z12, (DX)
	VMOVDQU32 Z13, 64(DX)

	// Row 7
	ADDQ R11, DX
	VMOVDQU32 Z14, (DX)
	VMOVDQU32 Z15, 64(DX)

	ADDQ $32, BX
	JMP loop_rhs_f16

store_output_f16_accum:
	// Accumulate:
	// Row 0
	VADDPS (DX), Z0, Z0
	VMOVDQU32 Z0, (DX)
	VADDPS 64(DX), Z1, Z1
	VMOVDQU32 Z1, 64(DX)

	// Row 1
	ADDQ R11, DX
	VADDPS (DX), Z2, Z2
	VMOVDQU32 Z2, (DX)
	VADDPS 64(DX), Z3, Z3
	VMOVDQU32 Z3, 64(DX)

	// Row 2
	ADDQ R11, DX
	VADDPS (DX), Z4, Z4
	VMOVDQU32 Z4, (DX)
	VADDPS 64(DX), Z5, Z5
	VMOVDQU32 Z5, 64(DX)

	// Row 3
	ADDQ R11, DX
	VADDPS (DX), Z6, Z6
	VMOVDQU32 Z6, (DX)
	VADDPS 64(DX), Z7, Z7
	VMOVDQU32 Z7, 64(DX)

	// Row 4
	ADDQ R11, DX
	VADDPS (DX), Z8, Z8
	VMOVDQU32 Z8, (DX)
	VADDPS 64(DX), Z9, Z9
	VMOVDQU32 Z9, 64(DX)

	// Row 5
	ADDQ R11, DX
	VADDPS (DX), Z10, Z10
	VMOVDQU32 Z10, (DX)
	VADDPS 64(DX), Z11, Z11
	VMOVDQU32 Z11, 64(DX)

	// Row 6
	ADDQ R11, DX
	VADDPS (DX), Z12, Z12
	VMOVDQU32 Z12, (DX)
	VADDPS 64(DX), Z13, Z13
	VMOVDQU32 Z13, 64(DX)

	// Row 7
	ADDQ R11, DX
	VADDPS (DX), Z14, Z14
	VMOVDQU32 Z14, (DX)
	VADDPS 64(DX), Z15, Z15
	VMOVDQU32 Z15, 64(DX)

	ADDQ $32, BX
	JMP loop_rhs_f16

next_lhs_f16:
	ADDQ $8, AX
	JMP loop_lhs_f16

done_f16:
	RET
