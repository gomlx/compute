// func avx2SmallNonTransposedTile4x16Float32Asm(
//     lRow0, lRow1, lRow2, lRow3 unsafe.Pointer,
//     rhsCol unsafe.Pointer,
//     contractingLen int,
//     rowStrideBytes int,
//     outRow0, outRow1, outRow2, outRow3 unsafe.Pointer)
TEXT ·avx2SmallNonTransposedTile4x16Float32Asm(SB), NOSPLIT, $0-88
	MOVQ lRow0+0(FP), R8
	MOVQ lRow1+8(FP), R9
	MOVQ lRow2+16(FP), R10
	MOVQ lRow3+24(FP), R11
	MOVQ rhsCol+32(FP), R12
	MOVQ contractingLen+40(FP), BX
	MOVQ rowStrideBytes+48(FP), R13
	MOVQ outRow0+56(FP), R14
	MOVQ outRow1+64(FP), R15
	MOVQ outRow2+72(FP), DI
	MOVQ outRow3+80(FP), SI

	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7

loop_k_f32:
	VBROADCASTSS (R8), Y10
	VBROADCASTSS (R9), Y11
	VBROADCASTSS (R10), Y12
	VBROADCASTSS (R11), Y13

	VMOVUPS (R12), Y8
	VMOVUPS 32(R12), Y9

	VFMADD231PS Y8, Y10, Y0
	VFMADD231PS Y9, Y10, Y1
	VFMADD231PS Y8, Y11, Y2
	VFMADD231PS Y9, Y11, Y3
	VFMADD231PS Y8, Y12, Y4
	VFMADD231PS Y9, Y12, Y5
	VFMADD231PS Y8, Y13, Y6
	VFMADD231PS Y9, Y13, Y7

	ADDQ $4, R8
	ADDQ $4, R9
	ADDQ $4, R10
	ADDQ $4, R11
	ADDQ R13, R12

	DECQ BX
	JNZ loop_k_f32

	VMOVUPS Y0, 0(R14)
	VMOVUPS Y1, 32(R14)
	VMOVUPS Y2, 0(R15)
	VMOVUPS Y3, 32(R15)
	VMOVUPS Y4, 0(DI)
	VMOVUPS Y5, 32(DI)
	VMOVUPS Y6, 0(SI)
	VMOVUPS Y7, 32(SI)
	RET

